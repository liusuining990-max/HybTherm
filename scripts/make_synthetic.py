"""Generate SYNTHETIC probe logs from the baseline model run.

    python scripts/make_synthetic.py

Requires results/baseline.npz from scripts/run_variants.py.
Writes data/synthetic/{baseline_run.csv, calibration_bath.csv, truth.json}.

These files imitate what the logger would record; they are generated, not
measured, and every file says so in its first line.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from hybtherm.geometry import BlockGeometry  # noqa: E402
from hybtherm.io import write_log  # noqa: E402
from hybtherm.model import SimConfig, SimResult  # noqa: E402
from hybtherm.synthetic import SensorModel, calibration_bath_log, probe_log_from_sim  # noqa: E402

PROBES = ["A1", "A6", "D6", "H12"]
NOTE = "SYNTHETIC DATA generated by HybTherm from the thermal model. NOT a measurement."


def load_result(path: Path) -> SimResult:
    d = np.load(path)
    cfg = SimConfig()
    return SimResult(
        config=cfg,
        t=d["t"],
        wells=d["wells"],
        control=d["control"],
        power=d["power"],
        mean=d["wells"].mean(axis=1),
        snapshot=d["snapshot"],
        well_names=BlockGeometry().well_names(),
    )


def main():
    out = ROOT / "data" / "synthetic"
    out.mkdir(parents=True, exist_ok=True)
    res = load_result(ROOT / "results" / "baseline.npz")
    sm = SensorModel()

    t, x, labels = probe_log_from_sim(res, PROBES, sm)
    write_log(out / "baseline_run.csv", t, x, labels, comments=[NOTE, "heater on 0-1800 s (setpoint 65 degC), off 1800-5400 s"])

    tc, xc, true_bath = calibration_bath_log(labels, sm)
    write_log(out / "calibration_bath.csv", tc, xc, labels, comments=[NOTE, "all probes in one stirred, insulated water bath"])

    truth = {
        "note": NOTE,
        "probe_offsets_degC": sm.offsets,
        "relative_offsets_degC": {
            k: round(v - float(np.mean(list(sm.offsets.values()))), 4) for k, v in sm.offsets.items()
        },
        "sensor_noise_std_degC": sm.noise_std,
        "sensor_lag_tau_s": sm.lag_tau,
        "quantisation_degC": 0.0625,
        "setpoint_degC": 65.0,
        "t_heater_off_s": 1800.0,
        "true_steady_well_means_degC": {
            p: round(float(res.wells[(res.t >= 1500) & (res.t <= 1800), res.well_names.index(p)].mean()), 4)
            for p in PROBES
        },
    }
    (out / "truth.json").write_text(json.dumps(truth, indent=2))
    print(json.dumps(truth, indent=2))


if __name__ == "__main__":
    main()
